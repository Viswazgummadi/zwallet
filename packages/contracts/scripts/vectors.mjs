// Regenerates derived contract data from reference implementations:
//   seed/*.json              fill fixed ids (UUIDv8 "seed:v1|" + system_key)
//   fixtures/uuid.json       UUIDv7/v8 and SMS-id vectors (ADR 0010)
//   fixtures/merge.json      expected merges for fixtures/merge.cases.json (ADR 0009/0017)
// Hand-written vectors (fixtures/money.json, fixtures/hlc.json) are not touched.
// Usage: node scripts/vectors.mjs [--check]

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { buildBackupVectors } from './backup-vectors.mjs';
import { buildSearchVectors } from './search-vectors.mjs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { uuidV7, uuidV8, smsId, seedId, transactionTagId, insightDismissalId, normalizeSender, normalizeBody } from '../lib/ids.mjs';
import { mergeRow, stringifyFieldHlc, MergeError } from '../lib/merge-reference.mjs';
import { loadContracts } from '../lib/contracts.mjs';

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const p = (rel) => path.join(PKG, rel);
const read = (rel) => JSON.parse(readFileSync(p(rel), 'utf8'));
const json = (v) => JSON.stringify(v, null, 2) + '\n';

// Merge specs come straight from the row schemas (same source as codegen).
const spec = (table) => {
  const s = read(`schema/${table}.json`);
  return { columns: Object.keys(s.properties), immutable: s['x-immutable'], groups: s['x-merge-groups'] };
};

function seeds() {
  const categories = read('seed/categories.json');
  for (const g of categories.groups) {
    g.id = seedId(g.system_key);
    for (const c of g.categories) c.id = seedId(c.system_key);
  }
  const tags = read('seed/tags.json');
  for (const t of tags.tags) t.id = seedId(t.system_key);
  return { 'seed/categories.json': categories, 'seed/tags.json': tags };
}

