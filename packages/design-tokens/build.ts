import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MODES, palette, shared, tokens, type Palette } from './resolve.ts';
import { iconOutputs } from './icons.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const KT = path.join(
  ROOT,
  'apps/android/core/designsystem/src/main/kotlin/dev/zwallet/core/designsystem/generated/ZwTokens.kt',
);
const CSS = path.join(ROOT, 'apps/web/src/ui/generated/tokens.css');
const TS = path.join(ROOT, 'apps/web/src/ui/generated/tokens.ts');

const header = (c: string) =>
  `${c} SPDX-License-Identifier: GPL-3.0-only\n${c} GENERATED by packages/design-tokens/build.ts from tokens.json. Do not edit.\n${c} Regenerate with: pnpm --filter @zwallet/design-tokens build\n`;
const camel = (s: string) => s.replace(/[_-]([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const kebab = (s: string) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/_/g, '-')
    .toLowerCase();

const palettes = Object.fromEntries(MODES.map((m) => [m, palette(m)])) as Record<string, Palette>;
const groups = Object.keys(palettes.light.categoryContainer);
const type = tokens.typography.scale as Record<
  string,
  { size: number; line: number; weight: number; tracking: number; features?: string }
>;
const num = (n: number) => (Number.isInteger(n) ? `${n}` : `${n}`);

// ── Kotlin ──────────────────────────────────────────────────────────────────────────────────
function kColor(hex: string): string {
  const h = hex.slice(1);
  const argb = h.length === 8 ? h.slice(6) + h.slice(0, 6) : `FF${h}`;
  return `Color(0x${argb})`;
}
function kFloat(n: number): string {
  const s = String(n);
  return `${s.includes('.') ? s : `${s}.0`}f`;
}

function kotlin(): string {
  const neutralKeys = Object.keys(palettes.light.neutrals);
  const m3Keys = Object.keys(palettes.light.m3);
  const fields = [
    ...neutralKeys.map((k) => `    val ${k}: Color,`),
    ...m3Keys.map((k) => `    val ${k}: Color,`),
    '    /** Categorical data slots 1–8, in fixed order (DESIGN §7.2). */',
    '    val dataCategorical: List<Color>,',
    '    val dataOther: Color,',
    '    val dataSingle: Color,',
    '    val dataGhost: Color,',
    '    val dataBand: Color,',
    '    val dataSequentialZero: Color,',
    '    val dataDivergingNeutral: Color,',
    '    /** Category group key → icon container (slot color at 16% over surface). */',
    '    val categoryContainer: Map<String, Color>,',
    '    /** Category group key → glyph color (≥ 3:1 against its container). */',
    '    val categoryGlyph: Map<String, Color>,',
  ];
  const instance = (p: Palette) => {
    const lines = [
      ...neutralKeys.map((k) => `            ${k} = ${kColor(p.neutrals[k])},`),
      ...m3Keys.map((k) => `            ${k} = ${kColor(p.m3[k as keyof Palette['m3']])},`),
      `            dataCategorical =\n                listOf(\n${p.dataviz.categorical.map((c) => `                    ${kColor(c)},`).join('\n')}\n                ),`,
      `            dataOther = ${kColor(p.dataviz.other)},`,
      `            dataSingle = ${kColor(p.dataviz.single)},`,
      `            dataGhost = ${kColor(p.dataviz.ghost)},`,
      `            dataBand = ${kColor(p.dataviz.band)},`,
      `            dataSequentialZero = ${kColor(p.dataviz.sequentialZero)},`,
      `            dataDivergingNeutral = ${kColor(p.dataviz.divergingNeutral)},`,
      `            categoryContainer =\n                mapOf(\n${groups.map((g) => `                    "${g}" to ${kColor(p.categoryContainer[g])},`).join('\n')}\n                ),`,
      `            categoryGlyph =\n                mapOf(\n${groups.map((g) => `                    "${g}" to ${kColor(p.categoryGlyph[g])},`).join('\n')}\n                ),`,
    ];
    return `    val ${p.mode}: ZwPalette =\n        ZwPalette(\n${lines.join('\n')}\n        )`;
  };
  const typeEntries = Object.entries(type)
    .map(
      ([k, t]) =>
        `        val ${k}: ZwTypeToken = ZwTypeToken(size = ${t.size}.sp, lineHeight = ${t.line}.sp, weight = ${t.weight}, trackingEm = ${kFloat(t.tracking)}, tabularFigures = ${t.features === 'tnum'})`,
    )
    .join('\n');
  const space = Object.entries(tokens.space as Record<string, number>)
    .map(([k, v]) => `        val s${k}: Dp = ${v}.dp`)
    .join('\n');
  const radius = Object.entries(tokens.radius as Record<string, number>)
    .map(([k, v]) => `        val ${k}: Dp = ${v}.dp`)
    .join('\n');
  const size = Object.entries(tokens.size as Record<string, number>)
    .map(([k, v]) => `        val ${k}: Dp = ${v}.dp`)
    .join('\n');
  const breakpoints = Object.entries(tokens.breakpoints as Record<string, number>)
    .map(([k, v]) => `        val ${k}: Dp = ${v}.dp`)
    .join('\n');
  const springs = Object.entries(
    tokens.motion.spring as Record<string, { damping: number; stiffness: number }>,
  )
    .map(
      ([k, v]) =>
        `        val ${k}: ZwSpring = ZwSpring(dampingRatio = ${kFloat(v.damping)}, stiffness = ${kFloat(v.stiffness)})`,
    )
    .join('\n');
  const durations = Object.entries(tokens.motion.duration as Record<string, number>)
    .map(([k, v]) => `        const val ${camel(k)}Ms: Int = ${v}`)
    .join('\n');
  const easings = Object.entries(tokens.motion.easing as Record<string, string>)
    .map(([k, v]) => {
      const [a, b, c, d] = v.match(/[\d.]+/g)!.map(Number);
      return `        val ${k}: CubicBezierEasing = CubicBezierEasing(${kFloat(a)}, ${kFloat(b)}, ${kFloat(c)}, ${kFloat(d)})`;
    })
    .join('\n');
  const seq = Object.entries(shared.sequential)
    .map(([k, v]) => `        val s${k}: Color = ${kColor(v)}`)
    .join('\n');

  return `${header('//')}package dev.zwallet.core.designsystem.generated

import androidx.compose.animation.core.CubicBezierEasing
import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.TextUnit
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

/** Every color of one theme mode. Built from tokens.json; read through ZwTheme, never directly. */
@Immutable
class ZwPalette(
${fields.join('\n')}
)

/** One step of the type scale (DESIGN §2.2). */
@Immutable
class ZwTypeToken(
    val size: TextUnit,
    val lineHeight: TextUnit,
    val weight: Int,
    val trackingEm: Float,
    val tabularFigures: Boolean,
)

/** A Material 3 Expressive spring (DESIGN §2.5). */
@Immutable
class ZwSpring(val dampingRatio: Float, val stiffness: Float)

object ZwTokens {
    const val BRAND_SEED: Long = 0x${kColor(tokens.brand.seed).slice(8, 16)}

${MODES.map((m) => instance(palettes[m])).join('\n\n')}

    object Sequential {
${seq}
    }

    object Diverging {
        val negative: Color = ${kColor(shared.divergingNegative)}
        val positive: Color = ${kColor(shared.divergingPositive)}
    }

    object Status {
${Object.entries(shared.status)
  .map(([k, v]) => `        val ${k}: Color = ${kColor(v)}`)
  .join('\n')}
    }

    const val AREA_WASH_OPACITY: Float = ${kFloat(shared.areaWashOpacity)}

    object Type {
${typeEntries}
    }

    object Space {
${space}
    }

    object Radius {
${radius}
    }

    object Size {
${size}
    }

    object Breakpoints {
${breakpoints}
    }

    object Motion {
${springs}
${durations}
${easings}
        const val CHART_STAGGER_MS: Int = ${tokens.motion.chartStagger}
    }
}
`.replace(/\n\n\n+/g, '\n\n');
}

// ── CSS ─────────────────────────────────────────────────────────────────────────────────────
function cssVars(p: Palette, indent: string): string {
  const v: string[] = [];
  for (const [k, c] of Object.entries(p.neutrals)) v.push(`--zw-color-${kebab(k)}: ${c};`);
  for (const [k, c] of Object.entries(p.m3)) v.push(`--zw-color-${kebab(k)}: ${c};`);
  p.dataviz.categorical.forEach((c, i) => v.push(`--zw-data-slot-${i + 1}: ${c};`));
  v.push(`--zw-data-other: ${p.dataviz.other};`);
  v.push(`--zw-data-single: ${p.dataviz.single};`);
  v.push(`--zw-data-ghost: ${p.dataviz.ghost};`);
  v.push(`--zw-data-band: ${p.dataviz.band};`);
  v.push(`--zw-data-sequential-zero: ${p.dataviz.sequentialZero};`);
  v.push(`--zw-data-diverging-neutral: ${p.dataviz.divergingNeutral};`);
  for (const g of groups) v.push(`--zw-category-${kebab(g)}-container: ${p.categoryContainer[g]};`);
  for (const g of groups) v.push(`--zw-category-${kebab(g)}-glyph: ${p.categoryGlyph[g]};`);
  return v.map((l) => indent + l).join('\n');
}
function cssDiff(p: Palette, base: Palette, indent: string): string {
  const a = cssVars(p, indent).split('\n');
  const b = new Set(cssVars(base, indent).split('\n'));
  return a.filter((l) => !b.has(l)).join('\n');
}

function css(): string {
  const rem = (px: number) => `${px / 16}rem`;
  const shared1: string[] = [];
  for (const [k, c] of Object.entries(shared.sequential)) shared1.push(`--zw-data-seq-${k}: ${c};`);
  shared1.push(`--zw-data-diverging-negative: ${shared.divergingNegative};`);
  shared1.push(`--zw-data-diverging-positive: ${shared.divergingPositive};`);
  for (const [k, c] of Object.entries(shared.status)) shared1.push(`--zw-status-${k}: ${c};`);
  shared1.push(`--zw-area-wash-opacity: ${shared.areaWashOpacity};`);
  for (const [k, v] of Object.entries(tokens.space as Record<string, number>))
    shared1.push(`--zw-space-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(tokens.radius as Record<string, number>))
    shared1.push(`--zw-radius-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(tokens.size as Record<string, number>))
    shared1.push(`--zw-size-${kebab(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(tokens.motion.duration as Record<string, number>))
    shared1.push(`--zw-duration-${k}: ${v}ms;`);
  for (const [k, v] of Object.entries(tokens.motion.easing as Record<string, string>))
    shared1.push(`--zw-easing-${kebab(k)}: ${v};`);
  shared1.push(
    `--zw-font-sans: ${tokens.typography.family.sans}, ${tokens.typography.family.fallback};`,
  );
  for (const [k, t] of Object.entries(type)) {
    shared1.push(`--zw-text-${kebab(k)}-size: ${rem(t.size)};`);
    shared1.push(`--zw-text-${kebab(k)}-line: ${rem(t.line)};`);
    shared1.push(`--zw-text-${kebab(k)}-weight: ${t.weight};`);
    shared1.push(`--zw-text-${kebab(k)}-tracking: ${t.tracking}em;`);
  }

  // Tailwind v4 theme: utilities resolve to the runtime variables, so dark mode needs no `dark:`.
  const theme: string[] = ['--color-*: initial;'];
  const colorNames = [...Object.keys(palettes.light.neutrals), ...Object.keys(palettes.light.m3)];
  for (const k of colorNames) theme.push(`--color-${kebab(k)}: var(--zw-color-${kebab(k)});`);
  for (const k of Object.keys(shared.status))
    theme.push(`--color-status-${k}: var(--zw-status-${k});`);
  theme.push('--color-transparent: transparent;', '--color-current: currentColor;');
  theme.push(`--font-sans: var(--zw-font-sans);`);
  for (const k of Object.keys(type)) {
    theme.push(`--text-${kebab(k)}: var(--zw-text-${kebab(k)}-size);`);
    theme.push(`--text-${kebab(k)}--line-height: var(--zw-text-${kebab(k)}-line);`);
    theme.push(`--text-${kebab(k)}--font-weight: var(--zw-text-${kebab(k)}-weight);`);
    theme.push(`--text-${kebab(k)}--letter-spacing: var(--zw-text-${kebab(k)}-tracking);`);
  }
  for (const k of Object.keys(tokens.radius)) theme.push(`--radius-${k}: var(--zw-radius-${k});`);
  for (const [k, v] of Object.entries(tokens.breakpoints as Record<string, number>)) {
    if (v > 0) theme.push(`--breakpoint-${k}: ${v}px;`);
  }
  theme.push(
    '--breakpoint-sm: initial;',
    '--breakpoint-md: initial;',
    '--breakpoint-lg: initial;',
    '--breakpoint-xl: initial;',
    '--breakpoint-2xl: initial;',
  );

  const ind = '  ';
  return `${header('/*')
    .replace(/\n(?=.)/g, '\n')
    .split('\n')
    .filter(Boolean)
    .map((l) => l.replace(/^\/\*/, '/*') + ' */')
    .join('\n')}

:root {
  color-scheme: light;
${cssVars(palettes.light, ind)}
${shared1.map((l) => ind + l).join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${cssVars(palettes.dark, ind + ind)}
  }
  :root:not([data-theme='light'])[data-amoled] {
${cssDiff(palettes.amoled, palettes.dark, ind + ind)}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${cssVars(palettes.dark, ind)}
}

:root[data-theme='dark'][data-amoled] {
${cssDiff(palettes.amoled, palettes.dark, ind)}
}

@theme inline {
${theme.map((l) => ind + l).join('\n')}
}
`;
}

// ── TypeScript ──────────────────────────────────────────────────────────────────────────────
function ts(): string {
  const pal = (p: Palette) => ({
    ...p.neutrals,
    ...p.m3,
    dataCategorical: p.dataviz.categorical,
    dataOther: p.dataviz.other,
    dataSingle: p.dataviz.single,
    dataGhost: p.dataviz.ghost,
    dataBand: p.dataviz.band,
    dataSequentialZero: p.dataviz.sequentialZero,
    dataDivergingNeutral: p.dataviz.divergingNeutral,
    categoryContainer: p.categoryContainer,
    categoryGlyph: p.categoryGlyph,
  });
  const motion = {
    spring: tokens.motion.spring,
    duration: tokens.motion.duration,
    easing: tokens.motion.easing,
    chartStagger: tokens.motion.chartStagger,
  };
  const j = (v: unknown) => JSON.stringify(v, null, 2);
  return `${header('//')}
export const palettes = ${j(Object.fromEntries(MODES.map((m) => [m, pal(palettes[m])])))} as const;

export type ThemeMode = keyof typeof palettes;
export type Palette = (typeof palettes)[ThemeMode];

export const sequential = ${j(shared.sequential)} as const;
export const diverging = ${j({ negative: shared.divergingNegative, positive: shared.divergingPositive })} as const;
export const status = ${j(shared.status)} as const;
export const areaWashOpacity = ${num(shared.areaWashOpacity)};
export const space = ${j(tokens.space)} as const;
export const radius = ${j(tokens.radius)} as const;
export const size = ${j(tokens.size)} as const;
export const breakpoints = ${j(tokens.breakpoints)} as const;
export const typeScale = ${j(type)} as const;
export const motion = ${j(motion)} as const;
`;
}

const outputs: Array<[string, string]> = [
  [KT, kotlin()],
  [CSS, css()],
  [TS, ts()],
  ...iconOutputs(ROOT, header),
];
const check = process.argv.includes('--check');
let stale = 0;
for (const [file, content] of outputs) {
  const rel = path.relative(ROOT, file);
  if (check) {
    const cur = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
    if (cur !== content) {
      console.error(`stale: ${rel}`);
      stale++;
    } else console.log(`up to date: ${rel}`);
  } else {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, content);
    console.log(`wrote ${rel}`);
  }
}
if (stale) {
  console.error('Generated tokens are stale. Run: pnpm --filter @zwallet/design-tokens build');
  process.exit(1);
}
