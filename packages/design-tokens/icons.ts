function categoryIcons(root: string): string[] {
  const seed = JSON.parse(
    readFileSync(path.join(root, 'packages/contracts/seed/categories.json'), 'utf8'),
  );
  const names = new Set<string>();
  for (const g of seed.groups) {
    names.add(g.icon);
    for (const c of g.categories) names.add(c.icon);
  }
  return [...names].sort();
}

/** App chrome [icon name, svg file stem] pairs, sorted. */
function appIconSet(): Array<[string, string]> {
  const out = new Map<string, string>();
  for (const [name, fill] of Object.entries(APP_ICONS)) {
    out.set(name, name);
    if (fill) out.set(`${name}_fill`, `${name}-fill`);
  }
  return [...out.entries()].sort(([a], [b]) => a.localeCompare(b));
}

/** App chrome plus category icons [icon name, svg file stem] pairs, sorted. */
function iconSet(root: string): Array<[string, string]> {
  const out = new Map<string, string>(appIconSet());
  for (const name of categoryIcons(root)) out.set(name, name);
  return [...out.entries()].sort(([a], [b]) => a.localeCompare(b));
}

/** Generated files holding Material Symbols artwork are Apache-2.0, not GPL (third-party notices). */
const APACHE_HEADER = (c: string) =>
  `${c} SPDX-License-Identifier: Apache-2.0
${c} Material Symbols Rounded path data, Copyright Google LLC (third-party notices).
${c} GENERATED by packages/design-tokens/build.ts. Do not edit.
${c} Regenerate with: pnpm --filter @zwallet/design-tokens build
`;

export function pathData(stem: string): string {
  const svg = readFileSync(path.join(SYMBOLS, 'rounded', `${stem}.svg`), 'utf8');
  if (!svg.includes('viewBox="0 -960 960 960"')) throw new Error(`${stem}: unexpected viewBox`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1) throw new Error(`${stem}: expected one path, got ${paths.length}`);
  return paths[0];
}

export function iconOutputs(root: string, header: (c: string) => string): Array<[string, string]> {
  const icons = iconSet(root).map(([name, stem]) => ({ name, d: pathData(stem) }));
  const drawableDir = 'apps/android/core/designsystem/src/main/res/drawable';
  const files: Array<[string, string]> = icons.map(({ name, d }) => [
    path.join(root, drawableDir, `zw_ic_${name}.xml`),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- SPDX-License-Identifier: Apache-2.0. Material Symbols Rounded "${name}", Copyright Google LLC. -->
<!-- GENERATED by packages/design-tokens/build.ts. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
        <path
            android:fillColor="@android:color/black"
            android:pathData="${d}" />
    </group>
</vector>
`,
  ]);

  const kt = `${header('//')}package dev.zwallet.core.designsystem.generated

import androidx.annotation.DrawableRes
import dev.zwallet.core.designsystem.R

/** Bundled Material Symbols Rounded glyphs by symbol name (DESIGN §2.4). */
object ZwIconNames {
    private val byName: Map<String, Int> =
        mapOf(
${icons.map(({ name }) => `            "${name}" to R.drawable.zw_ic_${name},`).join('\n')}
        )

    /** Drawable for a symbol name (e.g. a category's \`icon\`), or null when it isn't bundled. */
    @DrawableRes
    fun drawable(name: String): Int? = byName[name]
}
`;
  files.push([
    path.join(
      root,
      'apps/android/core/designsystem/src/main/kotlin/dev/zwallet/core/designsystem/generated/ZwIconNames.kt',
    ),
    kt,
  ]);

  // Web: chrome icons are imported by the shell; category icons live in their own module so they
  // stay out of the initial bundle until a screen that shows categories imports them.
  const tsModule = (pairs: Array<[string, string]>, what: string, exportName: string, typeName: string) =>
    `${APACHE_HEADER('//')}
/** ${what} (viewBox "0 -960 960 960"). */
export const ${exportName} = {
${pairs.map(([name, stem]) => `  ${name}: '${pathData(stem)}',`).join('\n')}
} as const;

export type ${typeName} = keyof typeof ${exportName};
`;
  const appTs = tsModule(appIconSet(), 'App chrome glyphs', 'icons', 'IconName').replace(
    '/** App chrome glyphs',
    "export const ICON_VIEWBOX = '0 -960 960 960';\n\n/** App chrome glyphs",
  );
  const categoryPairs: Array<[string, string]> = categoryIcons(root).map((n) => [n, n]);
  files.push([path.join(root, 'apps/web/src/ui/generated/icons.ts'), appTs]);
  files.push([
    path.join(root, 'apps/web/src/ui/generated/categoryIcons.ts'),
    tsModule(categoryPairs, 'Category glyphs, by seed icon name', 'categoryIcons', 'CategoryIconName'),
  ]);
  return files;
}
