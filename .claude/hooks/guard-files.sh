#!/usr/bin/env bash
# PreToolUse (Edit|Write): block edits to secrets, applied migrations, and generated golden files.
# Exit 2 = block; stderr is shown to Claude.
command -v jq >/dev/null 2>&1 || { echo "guard-files: jq not installed; skipping" >&2; exit 0; }

INPUT=$(cat)
FILE=$(echo "$INPUT" | jq -r '.tool_input.file_path // empty')
[ -z "$FILE" ] && exit 0
FILE="${FILE//\\//}"
ROOT="${CLAUDE_PROJECT_DIR:-$(pwd)}"
REL="${FILE#"$ROOT"/}"

block() { echo "Blocked: $REL — $1" >&2; exit 2; }

case "$REL" in
  *.env|*.env.*|*/.env|*/.env.*) block "secret env files are edited by the human only." ;;
  *.jks|*.keystore|*keystore.properties) block "signing material is never touched by Claude." ;;
  *gradle/wrapper/gradle-wrapper.jar) block "update the wrapper with ./gradlew wrapper, not by editing." ;;
  packages/contracts/expected/*|*/packages/contracts/expected/*)
    block "golden outputs are generated. Run: pnpm --filter @zwallet/contracts golden" ;;
esac

# Applied migrations are immutable: if the file is already committed, refuse.
if [[ "$REL" == supabase/migrations/* || "$REL" == */supabase/migrations/* ]]; then
  if [ -f "$FILE" ] && git -C "$(dirname "$FILE")" ls-files --error-unmatch "$(basename "$FILE")" >/dev/null 2>&1; then
    block "this migration is committed (applied). Create a new one: supabase migration new <name>"
  fi
fi
if [[ "$REL" == */schemas/*.json && "$REL" == apps/android/* ]]; then
  block "Room exported schemas are generated by the compiler. Bump the DB version and add a Migration instead."
fi
exit 0
